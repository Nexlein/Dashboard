export type ApiErrorCode = (typeof API_ERROR_CODES)[number];
const codes: ReadonlySet<string> = new Set(API_ERROR_CODES);

export function isApiErrorCode(value: unknown): value is ApiErrorCode {
    return typeof value === 'string' && codes.has(value);
}

/** Codes are attached by custom schema checks; native Zod failures use a fixed fallback. */
export function validationErrorCode(
    issue: { code: string; params?: Record<string, unknown> } | undefined,
): ApiErrorCode {
    const code = issue?.code === 'custom' ? issue.params?.apiErrorCode : undefined;
    return isApiErrorCode(code) ? code : 'VALIDATION_ERROR';
}

export function validationParams(code: ApiErrorCode, message: string) {
    return { message, params: { apiErrorCode: code } };
}
