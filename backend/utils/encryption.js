const crypto = require('crypto');

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 16;
const SALT = 'dashboard-widget-encryption';

let _key = null;
function getKey() {
    if (_key) return _key;

    // Use ENCRYPTION_KEY if provided, fallback to JWT_SECRET to avoid breaking existing setups
    const secret = process.env.ENCRYPTION_KEY || process.env.JWT_SECRET;
    if (!secret) {
        throw new Error('ENCRYPTION_KEY or JWT_SECRET must be set in environment variables');
    }

    // Derive a stable 32-byte key
    _key = crypto.scryptSync(secret, SALT, 32);
    return _key;
}

/**
 * Encrypts a JSON object into a secure format containing iv, authTag, and ciphertext.
 * @param {Object} params - The widget parameters to encrypt
 * @returns {Object} - An object suitable for JSON storage
 */
function encryptParams(params) {
    if (!params || typeof params !== 'object') {
        return params;
    }

    const text = JSON.stringify(params);
    const iv = crypto.randomBytes(IV_LENGTH);
    const cipher = crypto.createCipheriv(ALGORITHM, getKey(), iv);

    let encrypted = cipher.update(text, 'utf8', 'hex');
    encrypted += cipher.final('hex');

    const authTag = cipher.getAuthTag().toString('hex');

    return {
        _encrypted: true,
        iv: iv.toString('hex'),
        authTag,
        data: encrypted,
    };
}

/**
 * Decrypts a secure JSON payload back into the original widget parameters.
 * @param {Object} encryptedPayload - The object generated by encryptParams
 * @returns {Object} - The original widget parameters
 */
function decryptParams(encryptedPayload) {
    if (!encryptedPayload || !encryptedPayload._encrypted) {
        // Not an encrypted payload (legacy or plain)
        return encryptedPayload;
    }

    try {
        const decipher = crypto.createDecipheriv(
            ALGORITHM,
            getKey(),
            Buffer.from(encryptedPayload.iv, 'hex'),
        );

        decipher.setAuthTag(Buffer.from(encryptedPayload.authTag, 'hex'));

        let decrypted = decipher.update(encryptedPayload.data, 'hex', 'utf8');
        decrypted += decipher.final('utf8');

        return JSON.parse(decrypted);
    } catch (error) {
        console.error('Failed to decrypt widget parameters:', error.message);
        // Fallback: return an empty object or error indicator so the app doesn't crash completely
        return { error: 'Failed to decrypt parameters' };
    }
}

module.exports = {
    encryptJson: encryptParams,
    decryptJson: decryptParams,
    encryptParams,
    decryptParams,
};
