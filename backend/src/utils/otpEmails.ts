import { sendMail } from './mailer.ts';

export type OtpPurpose = 'email-verification' | 'forget-password' | 'change-email';

const CONTENT: Record<OtpPurpose, { subject: string; intro: string }> = {
    'email-verification': {
        subject: 'Votre code de vérification',
        intro: 'Saisissez ce code pour confirmer votre adresse email :',
    },
    'forget-password': {
        subject: 'Réinitialisation de votre mot de passe',
        intro: 'Saisissez ce code pour choisir un nouveau mot de passe :',
    },
    'change-email': {
        subject: 'Confirmez votre nouvelle adresse email',
        intro: 'Saisissez ce code pour utiliser cette adresse sur votre compte :',
    },
};

const EXPIRY =
    'Il expire dans 5 minutes. Si vous n’êtes pas à l’origine de cette demande, ignorez cet email.';

/** The email carrying a one-time code (Better Auth's emailOTP plugin, src/auth.ts). */
export function sendOtpEmail(to: string, otp: string, purpose: OtpPurpose) {
    const { subject, intro } = CONTENT[purpose];
    // `otp` is only digits (generated by Better Auth): safe in the HTML below.
    return sendMail({
        to,
        subject: `Dashboard : ${subject}`,
        text: `${intro}\n\n${otp}\n\n${EXPIRY}`,
        html: `<p>${intro}</p><p style="font-size:28px;font-weight:bold;letter-spacing:6px">${otp}</p><p>${EXPIRY}</p>`,
    });
}
